from __future__ import annotations

import argparse
import csv
import re
from dataclasses import dataclass
from pathlib import Path


ACCURACY_RE = re.compile(
    r"Epoch\s+(?P<epoch>\d+).*?accuracy_test=(?P<test>[0-9.]+),\s+accuracy_best=(?P<best>[0-9.]+)",
    re.IGNORECASE,
)


@dataclass
class ResultSummary:
    path: Path
    kind: str
    best_accuracy: float | None = None
    final_accuracy: float | None = None
    final_best: float | None = None
    final_epoch: int | None = None
    rows: int = 0


def parse_float(value: str) -> float | None:
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def summarize_csv(path: Path) -> ResultSummary:
    summary = ResultSummary(path=path, kind="csv")
    if "loss_sum" in path.name:
        return summary

    numeric_rows: list[list[float]] = []

    with path.open("r", encoding="utf-8", errors="ignore", newline="") as f:
        reader = csv.reader(f)
        for row in reader:
            values = [parse_float(item) for item in row]
            if values and all(value is not None for value in values):
                numeric_rows.append([value for value in values if value is not None])

    summary.rows = len(numeric_rows)
    if numeric_rows:
        last = numeric_rows[-1]
        if len(last) >= 2:
            # Most training CSV files append the running best accuracy in the final
            # column. The preceding metric may be OA, Kappa, or another loop-specific
            # value, so treat it only as a discovery hint.
            summary.final_accuracy = last[-2]
            summary.final_best = last[-1]
            summary.best_accuracy = max((row[-1] for row in numeric_rows if len(row) >= 2), default=None)
        elif len(last) == 1:
            summary.final_accuracy = last[0]
            summary.best_accuracy = max(row[0] for row in numeric_rows)
    return summary


def summarize_out(path: Path) -> ResultSummary:
    summary = ResultSummary(path=path, kind="out")
    matches = []
    with path.open("r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            match = ACCURACY_RE.search(line)
            if match:
                matches.append(match)

    summary.rows = len(matches)
    if matches:
        last = matches[-1]
        summary.final_epoch = int(last.group("epoch"))
        summary.final_accuracy = float(last.group("test"))
        summary.final_best = float(last.group("best"))
        summary.best_accuracy = max(float(match.group("best")) for match in matches)
    return summary


def write_outputs(root: Path, summaries: list[ResultSummary]) -> None:
    out_dir = root / "docs" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)

    csv_path = out_dir / "result_summary.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["path", "kind", "rows", "best_accuracy", "final_accuracy", "final_best", "final_epoch"])
        for item in summaries:
            writer.writerow(
                [
                    item.path.relative_to(root),
                    item.kind,
                    item.rows,
                    item.best_accuracy,
                    item.final_accuracy,
                    item.final_best,
                    item.final_epoch,
                ]
            )

    md_path = out_dir / "result_summary.md"
    top = [item for item in summaries if item.best_accuracy is not None]
    top.sort(key=lambda item: item.best_accuracy or -1, reverse=True)
    with md_path.open("w", encoding="utf-8") as f:
        f.write("# Result Summary\n\n")
        f.write("Generated by `scripts/summarize_results.py`.\n\n")
        f.write("This is a discovery aid. Verify source logs before using values in papers.\n\n")
        f.write("| Rank | Source | Kind | Rows | Best Acc. | Final Acc. | Final Best |\n")
        f.write("|---:|---|---|---:|---:|---:|---:|\n")
        for idx, item in enumerate(top[:50], start=1):
            f.write(
                f"| {idx} | `{item.path.relative_to(root)}` | {item.kind} | {item.rows} | "
                f"{item.best_accuracy if item.best_accuracy is not None else ''} | "
                f"{item.final_accuracy if item.final_accuracy is not None else ''} | "
                f"{item.final_best if item.final_best is not None else ''} |\n"
            )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".", help="Repository root")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    summaries: list[ResultSummary] = []

    for path in root.rglob("*"):
        if not path.is_file() or ".git" in path.parts:
            continue
        if path.suffix.lower() == ".csv":
            summaries.append(summarize_csv(path))
        elif path.suffix.lower() == ".out":
            summaries.append(summarize_out(path))

    write_outputs(root, summaries)
    print(f"Summarized {len(summaries)} result files.")
    print(f"Wrote {root / 'docs' / 'generated' / 'result_summary.csv'}")
    print(f"Wrote {root / 'docs' / 'generated' / 'result_summary.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
